function renderQuizView() {
  const qz = state.quiz;
  const q = qz.qs[qz.idx];
  const checked = qz.checked, selected = qz.selected;
  const progress = Math.round(((qz.idx + 1) / qz.qs.length) * 100);

  let feedback = '';
  if (checked) {
    const isCorrect = selected === q.a;
    feedback = `<div class="feedback-box ${isCorrect?'success':'danger'}">
      <strong>${isCorrect?'✅ إجابة صحيحة':'❌ إجابة خاطئة'}</strong><br>الإجابة: ${q.opts[q.a]}<br>الشرح: ${q.why}</div>`;
  }

  renderShell(`
    <div class="progress-bar"><div class="progress-fill" style="width:${progress}%"></div></div>
    <h2 class="question-text">${q.q}</h2>
    <div class="options-list">
      ${q.opts.map((o, i) => {
        let cls = 'option-btn';
        if (selected === i) cls += ' selected';
        if (checked && i === q.a) cls += ' correct';
        else if (checked && selected === i) cls += ' wrong';
        return `<button class="${cls}" data-ans="${i}" ${checked?'disabled':''}>
          <div class="option-letter">${['أ','ب','ج','د'][i]}</div><div>${o}</div></button>`;
      }).join('')}
    </div>
    ${feedback}
    <div style="margin-top:32px">
      ${checked 
        ? `<button class="btn btn-primary" data-action="next-q">${qz.idx === qz.qs.length - 1 ? 'النتيجة' : 'التالي ←'}</button>`
        : `<button class="btn btn-primary" data-action="check-q">تأكيد الإجابة</button>`}
    </div>
  `);
}

