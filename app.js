// ================== محرك الاختبارات ==================
function startQuiz(mode) {
  let qs = getQuestions(state.lesson, state.subject);
  if (!qs.length) return toast('لا توجد أسئلة متاحة');
  qs = [...qs].sort(() => Math.random() - 0.5);
  if (mode === 'practice') qs = qs.slice(0, 10);
  
  state.quiz = { qs, idx: 0, answers: [], selected: null, checked: false, mode };
  state.subView = 'quiz'; render();
}

function finishQuiz() {
  const qz = state.quiz;
  let correct = 0;
  qz.qs.forEach((q, i) => { if (qz.answers[i] === q.a) correct++; });
  
  const u = currentUser();
  u.points = (u.points || 0) + (correct * 10);
  save();

  const pct = Math.round((correct / qz.qs.length) * 100);
  state.resultData = { pct, pts: correct * 10 };
  state.subView = 'result'; render();
}

// ================== التوجيه (Router) ==================
function render() {
  if (!currentUser()) return renderAuth();
  
  if (state.page === 'home') renderHomeTab();
  else if (state.page === 'exams') renderExamsTab();
  else if (state.page === 'profile') renderProfileTab();
}

// ================== أحداث النقر (Events) ==================
app.addEventListener('click', (e) => {
  const drawerBtn = e.target.closest('[data-action="toggle-drawer"]');
  if (drawerBtn) { state.isDrawerOpen = !state.isDrawerOpen; render(); return; }
  
  const closeDrawerBtn = e.target.closest('[data-action="close-drawer"]');
  if (closeDrawerBtn) { state.isDrawerOpen = false; render(); return; }

  const navBtn = e.target.closest('[data-nav]');
  if (navBtn) {
    state.page = navBtn.dataset.nav;
    state.subView = null; 
    state.chatUser = null;
    state.quiz = null;
    state.isDrawerOpen = false;
    render(); 
    return;
  }

  const ansBtn = e.target.closest('[data-ans]');
  if (ansBtn && state.quiz && !state.quiz.checked) {
    state.quiz.selected = Number(ansBtn.dataset.ans); render(); return;
  }

  const btn = e.target.closest('[data-action]');
  if (!btn) return;

  const a = btn.dataset.action;
  
  if (a === 'nav-sub') {
    state.subView = btn.dataset.sub;
    if (btn.dataset.subject) state.subject = btn.dataset.subject;
    if (btn.dataset.lesson) state.lesson = btn.dataset.lesson;
    render();
  }

  if (a === 'start-quiz') { startQuiz(btn.dataset.mode); }
  if (a === 'check-q') { if (state.quiz.selected === null) return toast('اختر إجابة أولاً'); state.quiz.checked = true; state.quiz.answers[state.quiz.idx] = state.quiz.selected; render(); }
  if (a === 'next-q') {
    if (state.quiz.idx < state.quiz.qs.length - 1) { state.quiz.idx++; state.quiz.selected = null; state.quiz.checked = false; render(); }
    else finishQuiz();
  }
  
  if (a === 'open-chat') { state.chatUser = btn.dataset.user; state.subView = 'chat_room'; render(); }
  
  if (a === 'send-msg') {
    const inp = $('#msgInput'); if(inp && inp.value.trim()){
      const key = [currentUser().id, state.chatUser].sort().join('_');
      if(!store.chats[key]) store.chats[key] = [];
      store.chats[key].push({ sender: currentUser().id, text: inp.value.trim() });
      save(); render();
    }
  }

  if (a === 'send-notification') {
    const t = $('#notifText').value.trim();
    if(t){ store.notifications.unshift({ text: t, from: currentUser().name }); save(); toast('تم الإرسال'); state.subView = null; render(); }
  }
  
  if (a === 'delete-q') {
    store.customQuestions = store.customQuestions.filter(q => q.id !== btn.dataset.id); save(); render(); toast('تم الحذف');
  }

  if (a === 'logout') { 
    store.session = null; save(); state.page = 'home'; state.isDrawerOpen = false; render(); 
  }
});

app.addEventListener('keydown', (e) => {
  if (e.key === 'Enter' && e.target.id === 'msgInput') { e.preventDefault(); document.querySelector('[data-action="send-msg"]')?.click(); }
});

